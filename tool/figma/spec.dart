/// Condenses a Figma frame (node JSON) into a compact markdown spec:
/// a layout tree with size, auto-layout padding/gap, radius, fills, strokes,
/// shadows, text styles, component instances and icons.
///
/// First version (task 1.1); task 1.4 adds token mapping and the 6k-token
/// budget checks.
library;

typedef Json = Map<String, dynamic>;

/// Finds the node with [id] anywhere below [root].
Json? findNode(Json root, String id) {
  if (root['id'] == id) return root;
  for (final child in _children(root)) {
    final hit = findNode(child, id);
    if (hit != null) return hit;
  }
  return null;
}

/// Finds [id] in a `/files/:key/nodes` response.
Json? findInNodesResponse(Json response, String id) {
  final nodes = response['nodes'] as Json? ?? const {};
  for (final entry in nodes.values.cast<Json>()) {
    final document = entry['document'] as Json?;
    if (document == null) continue;
    final hit = findNode(document, id);
    if (hit != null) return hit;
  }
  return null;
}

String condenseFrame(Json frame, {String? title, int maxDepth = 12}) {
  final out = StringBuffer()
    ..writeln('# ${title ?? frame['name']}')
    ..writeln()
    ..writeln(
      'Figma node `${frame['id']}` · ${_size(frame)} · generated by '
      '`tool/figma_harvest.dart spec` from cached node JSON.',
    )
    ..writeln()
    ..writeln('## Layout tree')
    ..writeln();
  _writeNode(out, frame, 0, maxDepth);
  return out.toString();
}

void _writeNode(StringBuffer out, Json node, int depth, int maxDepth) {
  if (node['visible'] == false) return;
  final indent = '  ' * depth;
  out.writeln('$indent- ${describeNode(node)}');

  final type = node['type'];
  // Icons and vector art: one line is enough.
  if (_isIcon(node) || type == 'VECTOR' || type == 'BOOLEAN_OPERATION') return;
  if (depth >= maxDepth) {
    if (_children(node).isNotEmpty) out.writeln('$indent  - …');
    return;
  }

  final children = _children(node).where((c) => c['visible'] != false).toList();
  // Collapse runs of plain vectors (illustration fragments).
  final vectors = children.where(_isPlainVector).length;
  for (final child in children) {
    if (vectors > 3 && _isPlainVector(child)) continue;
    _writeNode(out, child, depth + 1, maxDepth);
  }
  if (vectors > 3) out.writeln('$indent  - VECTOR ×$vectors (illustration)');
}

/// One line per node, e.g.
/// `FRAME "Header" 428×56 · row pad 12/16 gap 10 · fill #FFFFFF · r16`.
String describeNode(Json node) {
  final type = node['type'] as String? ?? '?';
  final name = node['name'] as String? ?? '';
  final parts = <String>[];

  if (_isIcon(node)) {
    return 'icon `$name` ${_size(node)}${_fillsPart(node, prefix: ' · ')}';
  }

  if (type == 'TEXT') {
    final text = (node['characters'] as String? ?? '').replaceAll('\n', '⏎');
    parts.add('TEXT "${_clip(text, 80)}"');
    final style = node['style'] as Json? ?? const {};
    final size = style['fontSize'] as num?;
    final line = style['lineHeightPx'] as num?;
    parts.add(
      '${style['fontFamily'] ?? '?'} '
      '${_n(size)}/${_n(line)} w${style['fontWeight'] ?? '?'}'
      '${_letterSpacing(style)}${_align(style)}',
    );
  } else if (type == 'INSTANCE') {
    parts.add('INSTANCE "$name" ${_size(node)}');
    final props = _componentProps(node);
    if (props.isNotEmpty) parts.add(props);
  } else {
    parts.add('$type "$name" ${_size(node)}');
  }

  final layout = _layout(node);
  if (layout.isNotEmpty) parts.add(layout);
  final fills = _fillsPart(node);
  if (fills.isNotEmpty) parts.add(fills);
  final stroke = _stroke(node);
  if (stroke.isNotEmpty) parts.add(stroke);
  final radius = _radius(node);
  if (radius.isNotEmpty) parts.add(radius);
  final effects = _effects(node);
  if (effects.isNotEmpty) parts.add(effects);
  final opacity = node['opacity'] as num?;
  if (opacity != null && opacity < 1) parts.add('opacity ${_n(opacity)}');

  return parts.join(' · ');
}

List<Json> _children(Json node) =>
    (node['children'] as List<dynamic>? ?? const []).cast<Json>();

bool _isIcon(Json node) => (node['name'] as String? ?? '').startsWith('li:');

bool _isPlainVector(Json node) => const {
  'VECTOR',
  'ELLIPSE',
  'STAR',
  'LINE',
  'POLYGON',
}.contains(node['type']);

String _size(Json node) {
  final box = node['absoluteBoundingBox'] as Json?;
  if (box == null) return '';
  return '${_n(box['width'] as num?)}×${_n(box['height'] as num?)}';
}

String _layout(Json node) {
  final mode = node['layoutMode'] as String?;
  if (mode == null || mode == 'NONE') return '';
  final dir = mode == 'HORIZONTAL' ? 'row' : 'column';
  final t = _n(node['paddingTop'] as num? ?? 0);
  final r = _n(node['paddingRight'] as num? ?? 0);
  final b = _n(node['paddingBottom'] as num? ?? 0);
  final l = _n(node['paddingLeft'] as num? ?? 0);
  final pad = (t == b && l == r) ? (t == l ? t : '$t/$l') : '$t/$r/$b/$l';
  final gap = _n(node['itemSpacing'] as num? ?? 0);
  final align = [
    if (node['primaryAxisAlignItems'] case final String a when a != 'MIN')
      'main=${a.toLowerCase()}',
    if (node['counterAxisAlignItems'] case final String a when a != 'MIN')
      'cross=${a.toLowerCase()}',
  ];
  return '$dir pad $pad gap $gap${align.isEmpty ? '' : ' ${align.join(' ')}'}';
}

String _fillsPart(Json node, {String prefix = ''}) {
  final fills = _paints(node['fills']);
  if (fills.isEmpty) return '';
  return '${prefix}fill ${fills.join(' + ')}';
}

String _stroke(Json node) {
  final strokes = _paints(node['strokes']);
  if (strokes.isEmpty) return '';
  return 'stroke ${_n(node['strokeWeight'] as num? ?? 1)} ${strokes.join(' + ')}';
}

List<String> _paints(Object? raw) {
  final paints = (raw as List<dynamic>? ?? const []).cast<Json>();
  return [
    for (final p in paints)
      if (p['visible'] != false) _paint(p),
  ];
}

String _paint(Json paint) {
  final type = paint['type'] as String? ?? '?';
  final opacity = paint['opacity'] as num?;
  final alpha = opacity != null && opacity < 1 ? ' @${_n(opacity)}' : '';
  switch (type) {
    case 'SOLID':
      return '${hexColor(paint['color'] as Json? ?? const {})}$alpha';
    case 'IMAGE':
      return 'image$alpha';
    default:
      if (type.startsWith('GRADIENT')) {
        final stops = (paint['gradientStops'] as List<dynamic>? ?? const [])
            .cast<Json>()
            .map((s) => hexColor(s['color'] as Json? ?? const {}))
            .join('→');
        return '${type.substring(9).toLowerCase()}-gradient($stops)$alpha';
      }
      return type.toLowerCase();
  }
}

/// `{r,g,b,a}` in 0..1 → `#RRGGBB` (or `#RRGGBBAA` when translucent).
String hexColor(Json c) {
  String ch(String k) => (((c[k] as num?) ?? 0) * 255)
      .round()
      .clamp(0, 255)
      .toRadixString(16)
      .padLeft(2, '0')
      .toUpperCase();
  final a = (c['a'] as num?) ?? 1;
  return '#${ch('r')}${ch('g')}${ch('b')}${a < 1 ? ch('a') : ''}';
}

String _radius(Json node) {
  final corners = node['rectangleCornerRadii'] as List<dynamic>?;
  if (corners != null && corners.toSet().length > 1) {
    return 'r${corners.map((v) => _n(v as num)).join('/')}';
  }
  final r = node['cornerRadius'] as num?;
  return r == null || r == 0 ? '' : 'r${_n(r)}';
}

String _effects(Json node) {
  final effects = (node['effects'] as List<dynamic>? ?? const []).cast<Json>();
  final shown = [
    for (final e in effects)
      if (e['visible'] != false)
        switch (e['type']) {
          'DROP_SHADOW' || 'INNER_SHADOW' =>
            '${e['type'] == 'INNER_SHADOW' ? 'inner ' : ''}shadow '
                '${_n((e['offset'] as Json?)?['x'] as num? ?? 0)},'
                '${_n((e['offset'] as Json?)?['y'] as num? ?? 0)} '
                'blur ${_n(e['radius'] as num? ?? 0)} '
                'spread ${_n(e['spread'] as num? ?? 0)} '
                '${hexColor(e['color'] as Json? ?? const {})}',
          'LAYER_BLUR' => 'blur ${_n(e['radius'] as num? ?? 0)}',
          'BACKGROUND_BLUR' => 'bg-blur ${_n(e['radius'] as num? ?? 0)}',
          _ => '${e['type']}'.toLowerCase(),
        },
  ];
  return shown.join(', ');
}

String _componentProps(Json node) {
  final props = node['componentProperties'] as Json?;
  if (props == null || props.isEmpty) return '';
  final pairs = [
    for (final MapEntry(:key, :value) in props.entries)
      '${key.split('#').first}=${(value as Json)['value']}',
  ];
  return '{${pairs.join(', ')}}';
}

String _letterSpacing(Json style) {
  final ls = style['letterSpacing'] as num?;
  return ls == null || ls == 0 ? '' : ' ls ${_n(ls)}';
}

String _align(Json style) {
  final a = style['textAlignHorizontal'] as String?;
  return a == null || a == 'LEFT' ? '' : ' ${a.toLowerCase()}';
}

/// Compact number: `16`, `16.5`, `0.05`.
String _n(num? v) {
  if (v == null) return '?';
  final rounded = (v * 100).round() / 100;
  return rounded == rounded.roundToDouble()
      ? rounded.toInt().toString()
      : rounded.toString();
}

String _clip(String s, int max) =>
    s.length <= max ? s : '${s.substring(0, max)}…';
